use crate::plug::struct_set::FanControlMode;

pub struct ControlState {
    pub fan_cache: [i64; 2],
    pub ema_cpu: f64,
    pub ema_gpu: f64,
    pub ema_target_left: f64,
    pub ema_target_right: f64,
    pub active_mode: FanControlMode,
    pub constant_mode: bool,
    pub constant_speed: i64,
    pub office_cooldown_ticks: u32,
    pub gaming_hot_ticks: u32,
    pub cpu_hysteresis_anchor_temp: i64,
    pub gpu_hysteresis_anchor_temp: i64,
    pub last_power_source: &'static str,
    pub alert_cpu_high_count: u32,
    pub alert_gpu_high_count: u32,
    pub alert_cpu_recover_count: u32,
    pub alert_gpu_recover_count: u32,
    pub cpu_alert_active: bool,
    pub gpu_alert_active: bool,
    pub force_max_fan: bool,
    pub invalid_temp_streak: u8,
    pub released_to_auto_due_invalid: bool,
    pub cpu_fan_zero_rpm_streak: u8,
    pub gpu_fan_zero_rpm_streak: u8,
    pub cpu_fan_stalled: bool,
    pub gpu_fan_stalled: bool,
    pub wake_cooldown_ticks_remaining: u32,
    pub manual_mode_check_ticks: u32,
}

impl ControlState {
    pub fn new(mode: FanControlMode) -> Self {
        ControlState {
            fan_cache: [0i64; 2],
            ema_cpu: 0.0,
            ema_gpu: 0.0,
            ema_target_left: 0.0,
            ema_target_right: 0.0,
            active_mode: mode,
            constant_mode: false,
            constant_speed: 0,
            office_cooldown_ticks: 0,
            gaming_hot_ticks: 0,
            cpu_hysteresis_anchor_temp: 0,
            gpu_hysteresis_anchor_temp: 0,
            last_power_source: "unknown",
            alert_cpu_high_count: 0,
            alert_gpu_high_count: 0,
            alert_cpu_recover_count: 0,
            alert_gpu_recover_count: 0,
            cpu_alert_active: false,
            gpu_alert_active: false,
            force_max_fan: false,
            invalid_temp_streak: 0,
            released_to_auto_due_invalid: false,
            cpu_fan_zero_rpm_streak: 0,
            gpu_fan_zero_rpm_streak: 0,
            cpu_fan_stalled: false,
            gpu_fan_stalled: false,
            wake_cooldown_ticks_remaining: 0,
            manual_mode_check_ticks: 0,
        }
    }
}
